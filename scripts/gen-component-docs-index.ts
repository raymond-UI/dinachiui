/**
 * Writes `apps/docs/src/content/components/index.ts` and
 * `apps/docs/src/components/playgrounds/index.ts`: one static import per content file and
 * per playground, so the docs bundle every page without a glob. `inventory:check` fails
 * when either is stale.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const docs = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../apps/docs/src")
const dir = path.join(docs, "content/components")
export const playgroundDir = path.join(docs, "components/playgrounds")

const id = (slug: string, prefix = "doc_") => prefix + slug.replace(/-/g, "_")

export function playgroundSlugs(): string[] {
  return fs
    .readdirSync(playgroundDir)
    .filter((f) => f.endsWith(".tsx"))
    .map((f) => f.replace(/\.tsx$/, ""))
    .sort()
}

export function renderPlaygroundIndex(): string {
  const slugs = playgroundSlugs()
  return [
    "// Generated by scripts/gen-component-docs-index.ts. Run `pnpm docs:index` after adding a file.",
    'import type * as React from "react";',
    'import type { WorkbenchShell } from "@/components/component-page/workbench-types";',
    ...slugs.map((s) => `import ${id(s, "pg_")} from "./${s}";`),
    "",
    "export const playgrounds: Record<string, React.ComponentType<WorkbenchShell>> = {",
    ...slugs.map((s) => `  "${s}": ${id(s, "pg_")},`),
    "};",
    "",
  ].join("\n")
}

export const playgroundIndexPath = path.join(playgroundDir, "index.ts")

export function renderIndex(): string {
  const slugs = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.replace(/\.ts$/, ""))
    .sort()
  return [
    "// Generated by scripts/gen-component-docs-index.ts. Run `pnpm docs:index` after adding a file.",
    'import type { ComponentDoc } from "@/lib/component-pages/types";',
    ...slugs.map((s) => `import ${id(s)} from "./${s}";`),
    "",
    "export const componentDocs: Record<string, ComponentDoc> = {",
    ...slugs.map((s) => `  "${s}": ${id(s)},`),
    "};",
    "",
  ].join("\n")
}

export const indexPath = path.join(dir, "index.ts")

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(indexPath, renderIndex())
  fs.writeFileSync(playgroundIndexPath, renderPlaygroundIndex())
  console.log(`Wrote ${path.relative(process.cwd(), indexPath)} and ${path.relative(process.cwd(), playgroundIndexPath)}`)
}
